/**
 * Shared helper: calculates count of validated (verified + completed) civic contributions.
 * Consistently used by Profile Overview, ProfileShortcutsGrid, and RiwayatSummary.
 */
export const getValidatedContributionsCount = (items = CONTRIBUTION_HISTORY) =>
  items.filter((c) => c.status === 'verified' || c.status === 'completed').length

/**
 * Shared helper: calculates sum of confirmed XP from validated contributions.
 */
export const getTotalContributionXP = (items = CONTRIBUTION_HISTORY) =>
  items
    .filter((c) => c.status === 'verified' || c.status === 'completed')
    .reduce((sum, c) => sum + (c.xp || 0), 0)

export const CONTRIBUTION_SUMMARY = {
  totalCount: CONTRIBUTION_HISTORY.length,
  verifiedCount: getValidatedContributionsCount(),
  totalXP: getTotalContributionXP(),
}
